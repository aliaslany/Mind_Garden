// Groups entries round-robin into 12 "plots" for the archive page. This is
// just an organizational grouping for browsing, not tied to real dates —
// the home page picks randomly regardless of month.
export function getArchivePlots(monthNames) {
  const plots = monthNames.map((name, i) => ({ monthIndex: i, monthName: name, entries: [] }));
  CONTENT.forEach((entry, i) => {
    plots[i % monthNames.length].entries.push(entry);
  });
  return plots;
}

